/**
 * The site's single HTML-escaping implementation. Every renderer interpolates
 * user content through this — there is no framework auto-escaping here.
 */
export function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
